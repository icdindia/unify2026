import { Fragment } from 'react'
import { FRAMES, JOURNEYS, STEPS, stepName, type FrameKind } from '../../figma/frames'
import { FigmaLink } from '../../review/FigmaLink'
import { Link } from '../../router/Link'
import { useUiParam } from '../../router/uiParams'
import { GallerySection } from '../GalleryPage'
import type { GalleryMeta } from '../registry'
import './frame-map.css'

export const meta: GalleryMeta = {
  title: 'Frame map',
  figmaNodeIds: ['1707:115989'],
  group: 'Review harness',
  description:
    'Every Figma frame of the Chat + Artifacts page with the prototype URL that reproduces it, in Figma order: the handoff ' +
    'contract (src/figma/frames.ts, generated by tools/gen-frames.py from the build plan and the journey specs).',
}

const KIND: Record<FrameKind, string> = {
  N: 'New screen', S: 'Same screen, UI state', T: 'Time passing', R: 'Responsive width', G: 'Reference sheet', A: 'Alias', '-': 'Not a screen',
}

/** Same URL? Sorted keys and sorted seed / menu lists, as figma/frames.ts compares them. */
function urlKey(route: string): string {
  const [path, query = ''] = route.split('?')
  const items = [...new URLSearchParams(query)].map(([k, v]) => {
    if (k === 'seed') v = v.split(',').sort().join(',')
    if (k === 'menu') v = v.split(/[+ ]/).sort().join('+')
    return `${k}=${v}`
  })
  return path + '?' + items.sort().join('&')
}

export default function FrameMap() {
  const [journey, setJourney] = useUiParam('sheet')
  const shown = JOURNEYS.filter(j => !journey || j.id === journey)
  const distinct = new Set(FRAMES.map(f => urlKey(f.route))).size
  const unrouted = STEPS.filter(s => s.unrouted).length

  return (
    <>
      <div className="fm-summary">
        <p>
          {FRAMES.length} frames with a URL ({distinct} distinct URLs; aliases share one), {unrouted} without, {JOURNEYS.length} journeys.
          Kinds:{Object.entries(KIND).map(([k, v]) => <Fragment key={k}>{' '}<span className="fm-kind-key"><b>{k}</b> {v}</span></Fragment>)}
        </p>
        <label className="fm-filter">
          <span>Journey</span>
          <select value={journey ?? ''} onChange={e => setJourney(e.target.value || null)}>
            <option value="">All journeys</option>
            {JOURNEYS.map(j => <option key={j.id} value={j.id}>{j.id}: {j.title}</option>)}
          </select>
        </label>
      </div>

      {shown.map(j => {
        const steps = STEPS.filter(s => s.journey === j.id)
        return (
          <GallerySection key={j.id} title={`${j.id}: ${j.title}`}
                          description={j.card ? <FigmaLink nodeId={j.card} className="gallery-page__node">title card {j.card} ↗</FigmaLink> : undefined}>
            {steps.length === 0 ? (
              <p>{j.captured === false ? 'Not captured yet: no frames to map.' : 'No frames.'}</p>
            ) : (
              <ol className="fm-list">
                {steps.map(s => (
                  <li key={s.key} className={'fm-row' + (s.unrouted ? ' fm-row--off' : '')} data-frame={(s.frame ?? s.unrouted)?.nodeId}>
                    <span className="fm-step">{s.stepId}</span>
                    <span className="fm-kind" title={KIND[(s.frame?.kind ?? s.unrouted?.kind ?? '-') as FrameKind]}>{s.frame?.kind ?? s.unrouted?.kind ?? '-'}</span>
                    <span className="fm-label">
                      {s.label}
                      {s.frame?.aliasOf && <span className="fm-alias"> Same URL as {s.frame.aliasOf}.</span>}
                    </span>
                    <span className="fm-url">
                      {s.frame ? <Link to={s.frame.route} title={`Open ${stepName(s.frame)}`}>#{s.frame.route}</Link> : <em>{s.unrouted?.reason}</em>}
                    </span>
                    <span className="fm-node">
                      <FigmaLink nodeId={(s.frame ?? s.unrouted)!.nodeId} className="gallery-page__node">{(s.frame ?? s.unrouted)!.nodeId} ↗</FigmaLink>
                    </span>
                  </li>
                ))}
              </ol>
            )}
          </GallerySection>
        )
      })}
    </>
  )
}
