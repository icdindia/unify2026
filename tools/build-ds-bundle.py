#!/usr/bin/env python3
"""Build the single-file Unify CSS bundle and the atom catalogue.

  python3 tools/build-ds-bundle.py

Writes
  dist/unify-ds.css   (+ dist/parts/unify-core.css, unify-atoms-N.css, each under ~400 KB) tokens + overrides + typography + effects + every components/*/*.css (one file;
                      link it from any page or artifact, plus the Geist/Spectral/JetBrains Mono Google Fonts link)
  shared/ATOMS.md     every atom: what it is, its blocks, __elements and --modifiers (read this before building a screen)
dist/ is gitignored build output; the Design System artifact carries a copy as project/unify-ds.css."""
import glob, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
parts = []
for f in ["shared/tokens.css", "shared/tokens.live-overrides.css", "shared/typography.css", "shared/effects.css"]:
    parts.append(f"/* ===== {f} ===== */\n" + open(f).read())
atoms = sorted(d for d in os.listdir("components") if os.path.isfile(f"components/{d}/{d}.css"))
for a in atoms:
    parts.append(f"/* ===== components/{a}/{a}.css ===== */\n" + open(f"components/{a}/{a}.css").read())
os.makedirs("dist", exist_ok=True)
open("dist/unify-ds.css", "w").write("\n".join(parts))
# The Design System artifact keeps files under ~500 KB, so also write parts: core (tokens, type, effects)
# plus the atoms split into chunks of at most ~380 KB. Link them in order: core, atoms-1, atoms-2, ...
os.makedirs("dist/parts", exist_ok=True)
for old in glob.glob("dist/parts/*.css"):
    os.remove(old)
open("dist/parts/unify-core.css", "w").write("\n".join(parts[:4]))
chunks, cur, size = [], [], 0
for part in parts[4:]:
    if cur and size + len(part) > 380_000:
        chunks.append(cur); cur, size = [], 0
    cur.append(part); size += len(part)
if cur: chunks.append(cur)
for n, c in enumerate(chunks, 1):
    open(f"dist/parts/unify-atoms-{n}.css", "w").write("\n".join(c))

def strip(s):
    return re.sub(r"/\*.*?\*/", "", s, flags=re.S)

lines = ["# Atoms", "",
         "Generated by `tools/build-ds-bundle.py` from `components/*/*.css`. Class naming is BEM-like: `.block`, `.block__element`, `.block--modifier`.",
         "Link `dist/unify-ds.css` (or the copy in the Design System artifact) and use these classes; do not restyle them.", ""]
for a in atoms:
    raw = open(f"components/{a}/{a}.css").read()
    head = re.match(r"\s*/\*(.*?)\*/", raw, re.S)
    summary = ""
    if head:
        first = [l.strip(" -*\t") for l in head.group(1).strip().split("\n") if l.strip(" -*\t")]
        summary = re.sub(r"\s+", " ", first[0])[:160] if first else ""
    css = strip(raw)
    classes = sorted(set(re.findall(r"\.([a-z][a-z0-9]*(?:-[a-z0-9]+)*(?:__[a-z0-9-]+)?(?:--[a-z0-9-]+)?)", css)))
    blocks = sorted({c.split("__")[0].split("--")[0] for c in classes})
    nodes = sorted(set(re.findall(r"\b\d{2,6}:\d{2,7}\b", head.group(1) if head else "")))[:2]
    lines.append(f"## {a}" + (f"  \n{summary}" if summary else ""))
    if nodes: lines.append(f"Figma: {', '.join(nodes)}")
    for b in blocks:
        els = sorted({c.split("__")[1].split("--")[0] for c in classes if c.startswith(b + "__")})
        mods = sorted({"--" + c.split("--")[1] for c in classes if c.startswith(b) and "--" in c and c.split("__")[0].split("--")[0] == b})
        row = f"- `.{b}`"
        if els: row += "  elements: " + ", ".join(f"`__{e}`" for e in els[:14]) + (" …" if len(els) > 14 else "")
        if mods: row += "  modifiers: " + ", ".join(f"`{m}`" for m in mods[:16]) + (" …" if len(mods) > 16 else "")
        lines.append(row)
    lines.append("")
open("shared/ATOMS.md", "w").write("\n".join(lines))
print(f"{len(chunks)} atom parts; {len(atoms)} atoms; dist/unify-ds.css {os.path.getsize('dist/unify-ds.css')//1024} KB; shared/ATOMS.md")
