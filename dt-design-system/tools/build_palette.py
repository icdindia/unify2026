"""Add the DT palette (the 15 ODS secondary data-scheme hues) to the design system.

Input : source/figma-extract/dt-secondary.json   {hue: [[step, light, dark, odsToken], ...]}  (from ods-colour-tokens-all-schemes.txt)
Output: project/tokens.json           color.tokens += palette-<hue>-<step> {light, dark}
        foundations/dt-foundations.css  --palette-<hue>-<step>: light-dark(L, D) inside a marked :root block
        foundations/swatches.html       "DT palette" section (marked block)
Idempotent: re-running replaces the previous palette entries/blocks. Run after build_tokens.py.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HUES = ['aperitif', 'basketball', 'cheddar', 'dandelion', 'egg', 'frog', 'guacamole', 'hummingbird',
        'iguana', 'jacuzzi', 'kingfisher', 'lagoon', 'macaw', 'nebula', 'orchid']
STEPS = ['subtle', 'extra-dominant', 'dominant', 'base-subtle', 'base', 'recessive', 'extra-recessive']
STEP_USE = {
    'subtle': 'lightest tint: tinted backgrounds, chart fills behind text',
    'extra-dominant': 'light tint: hover on subtle surfaces, secondary chart series',
    'dominant': 'mid-light tone: tags, illustrations',
    'base-subtle': 'soft base: large tinted areas',
    'base': 'the hue itself: data-viz series, category colour, scheme background',
    'recessive': 'deeper tone: hover on base, text-safe accents on light',
    'extra-recessive': 'deepest tone: pressed state, text and icons on subtle tints',
}
src = json.load(open(os.path.join(ROOT, 'source', 'figma-extract', 'dt-secondary.json')))
pal = {h: {s[0]: (s[1].upper(), s[2].upper()) for s in src[h]} for h in HUES}

# ---------- tokens.json ----------
tp = os.path.join(ROOT, 'project', 'tokens.json')
t = json.load(open(tp))
toks = [x for x in t['color']['tokens'] if not x['name'].startswith('palette-')]
for h in HUES:
    for s in STEPS:
        L, D = pal[h][s]
        toks.append({'name': 'palette-%s-%s' % (h, s), 'value': {'light': L, 'dark': D},
                     'usage': 'DT palette · %s %s: %s. Same values as ODS data-scheme="%s".' % (h, s, STEP_USE[s], h)})
t['color']['tokens'] = toks
t['meta']['note'] = re.sub(r'\s*DT palette:.*$', '', t['meta'].get('note', '')) + \
    ' DT palette: palette-<hue>-<step> for the 15 ODS secondary hues (aperitif … orchid), 7 steps each, light + dark.'
json.dump(t, open(tp, 'w'), indent=1, ensure_ascii=False)

# ---------- dt-foundations.css ----------
cp = os.path.join(ROOT, 'foundations', 'dt-foundations.css')
css = open(cp).read()
css = re.sub(r'\n/\* ---------- DT palette:start.*?DT palette:end ---------- \*/\n', '\n', css, flags=re.S)
lines = ['', '/* ---------- DT palette:start (generated by tools/build_palette.py) ---------- */',
         '/* 15 ODS secondary hues x 7 steps, light-dark() pairs. Use for data-viz, categories and tints; never for text on white below recessive. */',
         ':root {']
for h in HUES:
    for s in STEPS:
        L, D = pal[h][s]
        lines.append('  --palette-%s-%s: light-dark(%s, %s);' % (h, s, L, D))
lines += ['}', '/* ---------- DT palette:end ---------- */', '']
css = css.rstrip('\n') + '\n' + '\n'.join(lines)
open(cp, 'w').write(css)

# ---------- swatches.html ----------
sp = os.path.join(ROOT, 'foundations', 'swatches.html')
html = open(sp).read()
html = re.sub(r'\s*<!-- DT palette:start -->.*?<!-- DT palette:end -->', '', html, flags=re.S)
rows = []
for h in HUES:
    cells = ''.join('<div class="pal-cell" style="background:var(--palette-%s-%s)" title="--palette-%s-%s"></div>' % (h, s, h, s) for s in STEPS)
    rows.append('<div class="pal-row"><b>%s</b><div class="pal-cells">%s</div></div>' % (h, cells))
block = ('\n  <!-- DT palette:start -->\n  <h2>DT palette</h2>\n'
         '  <p class="sub">15 ODS secondary hues, 7 steps each: %s. Tokens <code>--palette-&lt;hue&gt;-&lt;step&gt;</code>; switch Light/Dark above.</p>\n'
         '  <style>.pal-row{display:grid;grid-template-columns:120px 1fr;gap:12px;align-items:center;margin:6px 0}'
         '.pal-row b{font:700 .875rem/1.2 var(--font-family)}.pal-cells{display:grid;grid-template-columns:repeat(7,1fr);gap:6px}'
         '.pal-cell{height:40px;border-radius:8px}.pal-head{display:grid;grid-template-columns:120px repeat(7,1fr);gap:6px 12px;'
         'font:500 .75rem/1.2 var(--font-family);color:var(--colours-basic-text-recessive);margin-top:16px}'
         '@media (max-width:560px){.pal-row,.pal-head{grid-template-columns:72px 1fr}.pal-head span:not(:first-child){display:none}}</style>\n'
         '  <div class="pal-head"><span></span>%s</div>\n  %s\n  <!-- DT palette:end -->\n') % (
    ', '.join(STEPS), ''.join('<span>%s</span>' % s for s in STEPS), '\n  '.join(rows))
anchor = '  <h2>TeleNeo</h2>'
html = html.replace(anchor, block.lstrip('\n') + '\n' + anchor, 1) if anchor in html else html.replace('</main>', block + '</main>', 1)
open(sp, 'w').write(html)
print('palette tokens', len(HUES) * len(STEPS))
